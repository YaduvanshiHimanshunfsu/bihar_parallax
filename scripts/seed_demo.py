"""Create harmless, labelled demo cases for the Parallax judge flow.

The files are generated by this script; they are not operational evidence and must
never be represented as real crime-scene or victim material. Re-running the
script leaves an already populated demo case untouched.

Run from the project root:
    python scripts/seed_demo.py
    python scripts/seed_demo.py --data-dir C:\temp\parallax-demo
"""


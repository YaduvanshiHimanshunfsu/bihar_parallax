@dataclass(frozen=True)
class DemoSpec:
    reference: str
    title: str
    filename: str
    maker: Callable[[Path], None]
    analyser: str


def demo_settings(data_dir: Path | None) -> Settings:
    if data_dir is None:
        return Settings.from_environment()
    base = Settings.from_environment()
    root = data_dir.resolve()
    return Settings(
        project_root=base.project_root,
        data_root=root,
        database_path=root / "parallax.sqlite3",
        originals_dir=root / "uploads",
        derived_dir=root / "derived",
        reports_dir=root / "reports",
        web_dir=base.web_dir,
        max_upload_bytes=base.max_upload_bytes,
    )


def make_image(path: Path) -> None:
    image = Image.new("RGB", (640, 400), "#244e62")
    draw = ImageDraw.Draw(image)
    draw.rectangle((42, 48, 598, 354), outline="#dbedf5", width=3)
    draw.rectangle((386, 118, 516, 254), fill="#dcab4a")
    draw.text((64, 70), "TEAM-CREATED DEMO IMAGE", fill="#e7f4fb")
    exif = Image.Exif()
    exif[305] = "Adobe Photoshop (team-created demo)"
    exif[306] = "2026:10:26 13:00:00"
    exif[36867] = "2026:10:01 11:30:00"
    image.save(path, format="JPEG", quality=94, exif=exif)


def make_video(path: Path) -> None:
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"MJPG"), 5.0, (320, 180))
    if not writer.isOpened():
        raise RuntimeError("OpenCV could not create the team-created AVI demo file.")
    try:
        for index in range(24):
            # Intentionally repeats a static sequence then changes scene: this
            # exercises review leads; it is not asserted to be a real tamper.
            shade = 42 if index < 12 else 205
            frame = np.full((180, 320, 3), shade, dtype=np.uint8)
            cv2.putText(frame, "TEAM DEMO CCTV", (35, 40), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (230, 240, 245), 2)
            cv2.putText(frame, f"FRAME {index:02d}", (90, 112), cv2.FONT_HERSHEY_SIMPLEX, 1.0, (30, 170, 240), 2)
            writer.write(frame)
    finally:
        writer.release()


def make_audio(path: Path) -> None:
    sample_rate = 8_000
    silence = np.zeros(sample_rate * 2, dtype=np.int16)
    time = np.arange(sample_rate * 2) / sample_rate
    tone = (0.45 * np.sin(2 * np.pi * 440 * time) * np.iinfo(np.int16).max).astype(np.int16)
    with wave.open(str(path), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(sample_rate)
        output.writeframes(np.concatenate([silence, tone]).tobytes())


def upload(path: Path, case_id: str, store: EvidenceStore, service: CaseService):
    backing = tempfile.SpooledTemporaryFile(max_size=1024 * 1024)
    backing.write(path.read_bytes())
    backing.seek(0)
    content_types = {".jpg": "image/jpeg", ".avi": "video/x-msvideo", ".wav": "audio/wav"}
    upload_file = UploadFile(file=backing, filename=path.name, headers=Headers({"content-type": content_types[path.suffix.lower()]}))
    stored = store.persist(upload_file)
    return service.add_evidence(case_id, stored, actor="demo-seed")


def seed(settings: Settings) -> None:
    settings.create_directories()
    database = Database(settings.database_path)
    database.initialise()
    case_service = CaseService(database)
    evidence_store = EvidenceStore(settings.originals_dir, settings.max_upload_bytes)
    artifact_store = DerivedArtifactStore(settings.derived_dir)
    analysers = {
        "image": ImageAnalysisService(case_service, evidence_store, artifact_store),
        "video": VideoAnalysisService(case_service, evidence_store, artifact_store),
        "audio": AudioAnalysisService(case_service, evidence_store, artifact_store),
    }
    verifier = IntegrityVerificationService(case_service, evidence_store)
    assessor = AssessmentService(case_service)
    reporter = ReportService(case_service, ReportStore(settings.reports_dir))
    specs = [
        DemoSpec("DEMO-IMG-001", "Team-created image metadata and ELA review", "team_demo_image.jpg", make_image, "image"),
        DemoSpec("DEMO-VID-001", "Team-created CCTV temporal review", "team_demo_cctv.avi", make_video, "video"),
        DemoSpec("DEMO-AUD-001", "Team-created audio energy review", "team_demo_audio.wav", make_audio, "audio"),
        DemoSpec("DEMO-CUSTODY-001", "Team-created custody-chain verification", "team_demo_custody.jpg", make_image, "image"),
    ]
    with tempfile.TemporaryDirectory(prefix="parallax-demo-") as temporary_directory:
        temporary = Path(temporary_directory)
        for spec in specs:
            try:
                case = case_service.create_case(CaseCreate(reference=spec.reference, title=spec.title), actor="demo-seed")
            except DuplicateCaseError:
                case = next(item for item in case_service.list_cases() if item.reference == spec.reference)
            existing = case_service.get_case(case.id)
            if existing.evidence:
                if not any(report.report_format == "pdf" for report in existing.reports):
                    generated = reporter.generate(case.id, actor="demo-seed", formats=("pdf",))
                    print(f"{spec.reference}: added {generated[0].report_format.upper()} dossier to existing demo case.")
                else:
                    print(f"{spec.reference}: already populated; left unchanged.")
                continue
            source = temporary / spec.filename
            spec.maker(source)
            evidence = upload(source, case.id, evidence_store, case_service)
            analysis = analysers[spec.analyser].analyse(evidence.id, actor="demo-seed")
            verification = verifier.verify(evidence.id, actor="demo-seed")
            assessment = assessor.assess(case.id, actor="demo-seed")
            reports = reporter.generate(case.id, actor="demo-seed")
            print(
                f"{spec.reference}: {evidence.original_filename}; {len(analysis.findings)} findings; "
                f"hash match={verification.matches}; recommendation={assessment.outcome}; "
                f"reports={', '.join(report.report_format for report in reports)}"
            )
    print(f"Demo data directory: {settings.data_root}")
    print("Open http://127.0.0.1:8000 after starting the API.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed harmless team-created Parallax demo cases.")
    parser.add_argument("--data-dir", type=Path, help="Optional isolated data directory for the demo.")
    args = parser.parse_args()
    seed(demo_settings(args.data_dir))


if __name__ == "__main__":
    main()
